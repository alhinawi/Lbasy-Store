export const langs: Lang[] = ["ar", "en"];

export function isLang(v: string): v is Lang {
  return v === "ar" || v === "en";
}

/** Arabic lives at the root, English under /en. */
export function href(lang: Lang, path = "/") {
  const p = path.startsWith("/") ? path : `/${path}`;
  if (lang === "ar") return p;
  return p === "/" ? "/en" : `/en${p}`;
}

export function switchLangPath(pathname: string, to: Lang) {
  const bare = pathname.replace(/^\/en(?=\/|$)/, "") || "/";
  return href(to, bare);
}

export function formatPrice(n: number, lang: Lang) {
  const num = new Intl.NumberFormat(lang === "ar" ? "ar-EG" : "en-EG").format(n);
  return lang === "ar" ? `${num} جنيه` : `EGP ${num}`;
}

export function formatDate(iso: string, lang: Lang) {
  return new Intl.DateTimeFormat(lang === "ar" ? "ar-EG" : "en-GB", {
    day: "numeric",
    month: "long",
  }).format(new Date(iso));
}

export function pick(obj: object, field: string, lang: Lang): string {
  const o = obj as Record<string, unknown>;
  const v = o[`${field}_${lang}`] || o[`${field}_ar`];
  return typeof v === "string" ? v : "";
}

